/* Recovered selector-to-POL source map for Akira's visible fighter parts. */
#ifndef VF3_NATIVE_AKIRA_PARTS_H
#define VF3_NATIVE_AKIRA_PARTS_H

#include <stddef.h>
#include <stdint.h>

#include "fighter_view.h"

typedef enum {
    VF3_NATIVE_AKIRA_PART_EMPTY = 0,
    VF3_NATIVE_AKIRA_PART_MKAO_AKI,
    VF3_NATIVE_AKIRA_PART_ROB_AKI
} vf3_native_akira_part_source;

typedef struct {
    uint32_t selector;
    uint8_t source;
    uint8_t slot;
    uint8_t mesh_count;
} vf3_native_akira_selector_entry;

/* Eighteen live selector entries observed for the kind-0 Akira actor in
 * retained states 47 and 48. This identifies source POL meshes only; the
 * runtime pose still has to supply each entry's attachment transform. */
const vf3_native_akira_selector_entry *
vf3_native_akira_selector_map(size_t *count);

/* Draw Akira's selector-driven POL parts with the caller's current pose
 * matrices. Capture-derived matrices are for offline preview only; gameplay
 * must provide matrices generated by the native pose path. */
int vf3_native_akira_draw(
    SDL_Renderer *renderer,
    vf3_fighter_view *mkao_aki,
    vf3_fighter_view *rob_aki,
    const vf3_native_fighter *fighter,
    const float matrices[VF3_NATIVE_ATTACHMENT_COUNT]
                   [VF3_NATIVE_ATTACHMENT_MATRIX_FLOATS],
    const float scene_matrix[VF3_NATIVE_ATTACHMENT_MATRIX_FLOATS],
    float center_x, float ground_y, float scale);

#endif
