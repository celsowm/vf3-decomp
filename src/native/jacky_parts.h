/* Recovered native composition for Jacky's selector-driven model parts. */
#ifndef VF3_NATIVE_JACKY_PARTS_H
#define VF3_NATIVE_JACKY_PARTS_H

#include <stddef.h>
#include <stdint.h>

#include "fighter_view.h"

typedef enum {
    VF3_NATIVE_JACKY_PART_EMPTY = 0,
    VF3_NATIVE_JACKY_PART_MKAO_WO2,
    VF3_NATIVE_JACKY_PART_ROB_WO2
} vf3_native_jacky_part_source;

typedef struct {
    uint32_t selector;
    uint8_t source;
    uint8_t slot;
    uint8_t mesh_count;
} vf3_native_jacky_selector_entry;

/* This table is the exact 18-entry selector map recovered from both states
 * 47 and 48. Empty entries 5 and 9 have selector 0xffffffff. */
const vf3_native_jacky_selector_entry *
vf3_native_jacky_selector_map(size_t *count);

/* Draw the fixed Jacky composition from ordinary native POL views and the
 * caller's current pose matrices. Passing no scene matrix uses attachment
 * rows relative to row zero. Capture-derived matrices are for offline preview
 * only; gameplay must provide matrices generated by the native pose path. */
int vf3_native_jacky_draw(
    SDL_Renderer *renderer,
    vf3_fighter_view *mkao_wo2,
    vf3_fighter_view *rob_wo2,
    const vf3_native_fighter *fighter,
    const float matrices[VF3_NATIVE_ATTACHMENT_COUNT]
                   [VF3_NATIVE_ATTACHMENT_MATRIX_FLOATS],
    const float scene_matrix[VF3_NATIVE_ATTACHMENT_MATRIX_FLOATS],
    float center_x, float ground_y, float scale);

#endif
