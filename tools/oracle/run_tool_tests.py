"""Write a deterministic unittest transcript for the oracle tool tests.

The repo's audit tools pin a tool-test log by digest.  A raw
``python -m unittest`` transcript is not reproducible: it carries the elapsed
time, so re-running the same suite yields a different digest and breaks every
proof that references it.  This writer keeps the parts that carry meaning (the
per-test outcome and the test count) and drops the part that does not (the
wall-clock line), so the log is byte-stable across runs.
"""
import argparse
import io
from pathlib import Path
import sys
import unittest

DEFAULT_MODULES = [
    'test_capsule_extended',
    'test_capsule_pc_context',
    'test_capsule_repeat_batch',
    'test_capsule_repeat_tools',
    'test_capsule_select',
    'test_observer_record_limit',
    'test_entry_patch_builder',
    'test_campaign_tools',
]


def transcript(modules):
    loader = unittest.TestLoader()
    suite = unittest.TestSuite()
    for name in modules:
        suite.addTests(loader.loadTestsFromName(name))
    # unittest.TestSuite.run() blanks the slots it has already consumed
    # (CPython 3.11+), so the test identities have to be taken *before* the
    # run, not after it.
    ids = []

    def walk(item):
        for child in item:
            if isinstance(child, unittest.TestSuite):
                walk(child)
            elif child is not None:
                ids.append(child.id())
    walk(suite)
    ids.sort()
    result = unittest.TextTestRunner(stream=io.StringIO(), verbosity=0).run(suite)
    outcome = {}
    for test, _ in result.failures:
        outcome[test.id()] = 'FAIL'
    for test, _ in result.errors:
        outcome[test.id()] = 'ERROR'
    for test, _ in result.skipped:
        outcome[test.id()] = 'skipped'
    out = ['# VF3 oracle tool tests - deterministic transcript',
           '# generated by tools/oracle/run_tool_tests.py',
           '# the elapsed time is deliberately omitted so the digest is stable']
    for test_id in ids:
        out.append(f'{test_id} ... {outcome.get(test_id, "ok")}')
    out.append('-' * 70)
    out.append(f'Ran {result.testsRun} tests')
    out.append('')
    out.append('OK' if result.wasSuccessful() else 'FAILED')
    return '\n'.join(out) + '\n', result.wasSuccessful()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--module', action='append', default=[])
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    text, ok = transcript(args.module or DEFAULT_MODULES)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding='utf-8')
    print(f'{args.out}: {"OK" if ok else "FAILED"}')
    return 0 if ok else 1


if __name__ == '__main__':
    raise SystemExit(main())
