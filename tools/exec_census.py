#!/usr/bin/env python3
"""exec_census.py - who owns every executed block entry in a vf3trace stream?

Reads one or more vf3trace u64 streams (pc = rec>>16, P2 alias
0x0C000000..0x0C1FFFFF folded to 0x8C......) and classifies each executed
2-byte slot of the 1ST_READ image as
  ported    - inside a baseline function the ledger marks ported*
  unported  - inside a baseline function that is not ported
  gap       - inside NO baseline function (uncatalogued code)
Gap runs are clustered (<= --join slots apart), tagged ('stub' when the run
is only rts/nop, 'ledger' when a ledger-ported range already covers it) and
written as an *extension* baseline - the frozen baseline CSV is never edited.

NOTE: a vf3trace record is a basic-block ENTRY, not an instruction. All
weights here are block-entry weights.

Outputs (extract/analysis/census/):
  hits_<trace>.npy        per-slot hit counts (cache)
  census_<trace>.csv      per-owner rows (kind, entry, size, unique, hits)
  gaps_<trace>.csv        clustered gap runs
  funcs_extended.csv      gap runs from all traces merged, as baseline rows
Report (stdout, --md writes docs/re/exec_census.md).

Usage: python tools/exec_census.py trace_fight1.bin [trace_melee.bin ...] [--md]
"""
from __future__ import annotations

import argparse
import csv
import struct
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
AN = REPO / 'extract' / 'analysis'
OUT = AN / 'census'
BASE = 0x8C010000
SZ = 0x100000
SLOTS = SZ // 2


def load_ledger():
    ported, ranges = set(), []
    for r in csv.DictReader(open(REPO / 'docs' / 'decomp_status.csv', newline='')):
        if not r['status'].startswith('ported'):
            continue
        e = int(r['entry'], 16)
        ported.add(e)
        s = int(r['size'] or 0)
        if s > 0:
            ranges.append((e, s))
    return ported, ranges


def load_baseline():
    fn = []
    for r in csv.DictReader(open(AN / 'funcs_1ST_READ.unsc.bin.csv', newline='')):
        e = int(r['entry'], 16)
        s = int(r['size'])
        if s > 0:
            fn.append((e, s, r.get('name', '')))
    fn.sort()
    return fn


def trace_hits(path: Path) -> np.ndarray:
    cache = OUT / f'hits_{path.stem}.npy'
    if cache.exists() and cache.stat().st_mtime >= path.stat().st_mtime:
        return np.load(cache)
    hits = np.zeros(SLOTS, np.int64)
    mm = np.memmap(path, dtype=np.uint64, mode='r')
    CH = 1 << 24
    for i in range(0, len(mm), CH):
        c = np.asarray(mm[i:i + CH])
        pc = ((c >> np.uint64(16)) & np.uint64(0xFFFFFFFF)).astype(np.int64)
        pc = np.where((pc >= 0x0C000000) & (pc < 0x0C200000), pc | 0x80000000, pc)
        m = (pc >= BASE) & (pc < BASE + SZ)
        hits += np.bincount((pc[m] - BASE) // 2, minlength=SLOTS)
    OUT.mkdir(parents=True, exist_ok=True)
    np.save(cache, hits)
    return hits


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('traces', nargs='+')
    ap.add_argument('--join', type=int, default=16, help='merge gap runs <= N slots apart')
    ap.add_argument('--md', action='store_true')
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    img = (AN.parent / 'exe' / '1ST_READ.unsc.bin').read_bytes()
    words = np.frombuffer(img[: len(img) // 2 * 2], dtype='<u2')

    ported, lranges = load_ledger()
    base = load_baseline()
    owner = np.full(SLOTS, -1, np.int32)
    for i, (e, s, _) in enumerate(base):
        owner[(e - BASE) // 2:(e + s - BASE + 1) // 2] = i
    isp = np.array([e in ported for e, _, _ in base])
    led = np.zeros(SLOTS, bool)
    for e, s in lranges:
        if BASE <= e < BASE + SZ:
            led[(e - BASE) // 2:(e + s - BASE + 1) // 2] = True

    ext_runs = {}
    md = ['# Execution census (block-entry weighted)\n',
          'Generated by `tools/exec_census.py`. A trace record is a block entry, '
          'not an instruction.\n']
    for t in a.traces:
        p = Path(t) if Path(t).exists() else AN / t
        hits = trace_hits(p)
        seen = hits > 0
        tot = hits.sum()
        inb = owner >= 0
        cls_p = inb & np.where(owner >= 0, isp[np.maximum(owner, 0)], False)
        cls_u = inb & ~cls_p
        gap = ~inb
        stat = lambda m: (int((seen & m).sum()), int(hits[m].sum()))
        sp, su, sg = stat(cls_p), stat(cls_u), stat(gap)
        gl = seen & gap & led
        print(f'== {p.name}: {tot:,} records, {int(seen.sum())} unique block entries')
        for name, (u, h) in (('ported', sp), ('unported', su), ('gap', sg)):
            print(f'  {name:9s} uniq={u:6d} ({100*u/max(1,int(seen.sum())):5.1f}%)  '
                  f'hits={h:>13,} ({100*h/max(1,tot):5.1f}%)')
        print(f'  (gap slots already inside a ledger-ported range: {int(gl.sum())})')
        md.append(f'\n## {p.name}\n\n{tot:,} records, {int(seen.sum())} unique block entries.\n\n'
                  '| class | unique entries | hits |\n|---|---:|---:|\n')
        for name, (u, h) in (('ported', sp), ('unported baseline', su), ('uncatalogued gap', sg)):
            md.append(f'| {name} | {u} ({100*u/max(1,int(seen.sum())):.1f}%) | '
                      f'{h:,} ({100*h/max(1,tot):.1f}%) |\n')

        # per-owner csv
        rows = []
        for i, (e, s, nm) in enumerate(base):
            lo, hi = (e - BASE) // 2, (e + s - BASE + 1) // 2
            h = int(hits[lo:hi].sum())
            if h:
                rows.append(('ported' if isp[i] else 'unported', e, s,
                             int(seen[lo:hi].sum()), h))
        rows.sort(key=lambda r: -r[4])
        with open(OUT / f'census_{p.stem}.csv', 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['kind', 'entry', 'size', 'unique_entries', 'hits'])
            for r in rows:
                w.writerow([r[0], f'0x{r[1]:08x}', r[2], r[3], r[4]])

        # gap runs
        idx = np.nonzero(seen & gap)[0]
        runs = []
        if len(idx):
            s0 = pv = int(idx[0])
            for x in idx[1:]:
                x = int(x)
                if x - pv > a.join:
                    runs.append((s0, pv)); s0 = x
                pv = x
            runs.append((s0, pv))
        gr = []
        for lo, hi in runs:
            hi2 = hi + 1
            w16 = words[lo:hi2]
            stub = bool(np.all((w16 == 0x000B) | (w16 == 0x0009)))
            kind = 'stub' if stub else ('ledger' if led[lo:hi2].any() else 'code')
            h = int(hits[lo:hi2].sum())
            gr.append((BASE + lo * 2, (hi2 - lo) * 2, kind, int(seen[lo:hi2].sum()), h))
            ext_runs.setdefault((BASE + lo * 2, (hi2 - lo) * 2), kind)
        gr.sort(key=lambda r: -r[4])
        with open(OUT / f'gaps_{p.stem}.csv', 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['entry', 'span', 'kind', 'unique_entries', 'hits'])
            for r in gr:
                w.writerow([f'0x{r[0]:08x}', r[1], r[2], r[3], r[4]])
        kc = {}
        for r in gr:
            k = kc.setdefault(r[2], [0, 0, 0])
            k[0] += 1; k[1] += r[1]; k[2] += r[4]
        print('  gap runs by kind:', {k: tuple(v) for k, v in kc.items()}, '(count, span B, hits)')
        md.append('\nGap runs (uncatalogued executed code), by kind:\n\n'
                  '| kind | runs | span B | hits |\n|---|---:|---:|---:|\n')
        for k, v in kc.items():
            md.append(f'| {k} | {v[0]} | {v[1]} | {v[2]:,} |\n')
        md.append('\nTop gap runs:\n\n| entry | span | kind | hits |\n|---|---:|---|---:|\n')
        for r in gr[:12]:
            md.append(f'| `0x{r[0]:08x}` | {r[1]} | {r[2]} | {r[4]:,} |\n')
        md.append('\nTop unported baseline owners:\n\n| entry | size | hits |\n|---|---:|---:|\n')
        for r in [r for r in rows if r[0] == 'unported'][:10]:
            md.append(f'| `0x{r[1]:08x}` | {r[2]} | {r[4]:,} |\n')

    with open(OUT / 'funcs_extended.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['entry', 'size', 'kind'])
        for (e, s), k in sorted(ext_runs.items()):
            w.writerow([f'0x{e:08x}', s, k])
    print(f'funcs_extended.csv: {len(ext_runs)} gap runs')
    if a.md:
        (REPO / 'docs' / 're' / 'exec_census.md').write_text(''.join(md), encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
