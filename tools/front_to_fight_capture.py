#!/usr/bin/env python3
"""Capture repeatable frame checkpoints while navigating VF3's front end.

The tool builds a frame-clock VF3_PLAY script with alternating Start/A
button taps and savestates, then delegates the isolated emulator run to
``flycast_capture.py``. The button schedule is a navigation probe, not an
assertion that a particular menu path or fight state was reached.

Example:
  python tools/front_to_fight_capture.py \
      --out extract/analysis/front_to_fight_probe_v1

Reuse a KEYF-only timeline while inserting checkpoint saves:
  python tools/front_to_fight_capture.py \
      --input-script tools/vf3_play_boot_mix.txt \
      --out extract/analysis/front_to_fight_bootmix_v1 \
      --frames 4800 --checkpoint 300
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
ANALYSIS = ROOT / "extract" / "analysis"
CAPTURE = ROOT / "tools" / "flycast_capture.py"

# vf3script KEYF masks use Flycast/KOS Dreamcast button bits. The bits are
# listed as pressed buttons here; the Maple wire representation is active-low.
DC_BTN_A = 0x0004
DC_BTN_START = 0x0008


def integer(text: str) -> int:
    try:
        value = int(text, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"invalid integer: {text}") from exc
    if value < 0:
        raise argparse.ArgumentTypeError("value must be nonnegative")
    return value


def schedule(frames: int, start_frame: int, tap_interval: int,
             tap_length: int, start_mask: int, confirm_mask: int,
             checkpoint: int, tap_until: int | None = None) -> str:
    events: dict[int, list[str]] = {0: ["KEYF 0x0"]}

    def add(frame: int, command: str) -> None:
        events.setdefault(frame, []).append(command)

    index = 0
    frame = start_frame
    last_tap = frames - 1 if tap_until is None else tap_until
    while frame <= last_tap and frame + tap_length < frames - 1:
        mask = start_mask if index % 2 == 0 else confirm_mask
        add(frame, f"KEYF 0x{mask:x}")
        add(frame + tap_length, "KEYF 0x0")
        index += 1
        frame += tap_interval

    for point in range(checkpoint, frames - 1, checkpoint):
        add(point, f"SAVEF {point // checkpoint}")

    rows = ["# Generated by tools/front_to_fight_capture.py"]
    rows.extend(f"{frame} {command}" for frame in sorted(events)
                for command in events[frame])
    rows.append(f"{frames - 1} EXITF")
    return "\n".join(rows) + "\n"


def schedule_from_script(path: Path, frames: int, checkpoint: int) -> str:
    """Add checkpoint saves to a KEYF-only timeline, owning its EXITF."""
    events: dict[int, list[str]] = {0: ["KEYF 0x0"]}
    for line_number, source_line in enumerate(
            path.read_text(encoding="utf-8").splitlines(), 1):
        line = source_line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        try:
            frame = int(parts[0], 0)
        except (ValueError, IndexError) as exc:
            raise ValueError(f"{path}:{line_number}: invalid frame-clock command") from exc
        if len(parts) == 2 and parts[1].upper() == "EXITF":
            continue
        if len(parts) != 3 or parts[1].upper() != "KEYF":
            raise ValueError(f"{path}:{line_number}: only KEYF and final EXITF are supported")
        try:
            mask = int(parts[2], 0)
        except ValueError as exc:
            raise ValueError(f"{path}:{line_number}: invalid KEYF mask") from exc
        if frame < 0 or frame >= frames - 1 or not 0 <= mask <= 0xFFFF:
            raise ValueError(f"{path}:{line_number}: frame or KEYF mask is out of range")
        events.setdefault(frame, []).append(f"KEYF 0x{mask:x}")
    for point in range(checkpoint, frames - 1, checkpoint):
        events.setdefault(point, []).append(f"SAVEF {point // checkpoint}")
    rows = ["# Generated by tools/front_to_fight_capture.py"]
    rows.extend(f"{frame} {command}" for frame in sorted(events)
                for command in events[frame])
    rows.append(f"{frames - 1} EXITF")
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path,
                        help="new isolated output directory under extract/analysis")
    parser.add_argument("--emulator", type=Path,
                        default=ROOT / "tools" / "emu" / "flycast-build" / "flycast_v3.exe")
    parser.add_argument("--rom", type=Path, default=ROOT / "rom" / "vf3.gdi")
    parser.add_argument("--input-script", type=Path,
                        help="reuse a KEYF timeline, adding periodic savestates")
    parser.add_argument("--frames", type=int, default=5400,
                        help="frame-clock run length (default: 5400)")
    parser.add_argument("--start-frame", type=int, default=900,
                        help="first menu tap frame (default: 900)")
    parser.add_argument("--tap-interval", type=int, default=150,
                        help="frames between alternating taps (default: 150)")
    parser.add_argument("--tap-length", type=int, default=15,
                        help="duration of each button tap (default: 15)")
    parser.add_argument("--tap-until", type=int,
                        help="last tap start frame; omit to tap through the run")
    parser.add_argument("--start-mask", type=integer, default=DC_BTN_START,
                        help="pressed-button mask for Start (default: 0x8)")
    parser.add_argument("--confirm-mask", type=integer, default=DC_BTN_A,
                        help="pressed-button mask for A (default: 0x4)")
    parser.add_argument("--checkpoint", type=int, default=600,
                        help="savestate interval in frames (default: 600)")
    parser.add_argument("--timeout", type=int, default=1200,
                        help="maximum emulator runtime in seconds (default: 1200)")
    args = parser.parse_args(argv)

    out = args.out.resolve() if args.out.is_absolute() else (ROOT / args.out).resolve()
    emulator = args.emulator.resolve() if args.emulator.is_absolute() else (ROOT / args.emulator).resolve()
    rom = args.rom.resolve() if args.rom.is_absolute() else (ROOT / args.rom).resolve()
    try:
        out.relative_to(ANALYSIS.resolve())
    except ValueError:
        parser.error("--out must be inside extract/analysis")
    if args.frames < 2 or args.start_frame < 0 or args.tap_interval <= 0 or \
            args.tap_length <= 0 or args.checkpoint <= 0 or \
            args.checkpoint >= args.frames - 1 or args.timeout <= 0:
        parser.error("frame, tap, checkpoint, and timeout values must be positive")
    if args.tap_until is not None and not args.start_frame <= args.tap_until < args.frames - 1:
        parser.error("--tap-until must be between --start-frame and the final frame")
    if args.start_mask > 0xFFFF or args.confirm_mask > 0xFFFF:
        parser.error("button masks must fit in 16 bits")
    if args.start_mask == args.confirm_mask:
        parser.error("Start and confirm masks must differ")
    if args.start_frame + args.tap_length >= args.frames - 1:
        parser.error("the first tap must end before EXITF")
    if not CAPTURE.is_file():
        parser.error(f"capture runner is missing: {CAPTURE}")
    if not emulator.is_file():
        parser.error(f"emulator does not exist: {emulator}")
    if not rom.is_file():
        parser.error(f"disc image does not exist: {rom}")
    if out.exists():
        parser.error(f"refusing to replace existing output directory: {out}")

    out.parent.mkdir(parents=True, exist_ok=True)
    play = out.parent / f"{out.name}.front_to_fight.play.txt"
    if play.exists():
        parser.error(f"refusing to replace existing play script: {play}")
    try:
        if args.input_script:
            input_script = args.input_script.resolve() if args.input_script.is_absolute() \
                else (ROOT / args.input_script).resolve()
            if not input_script.is_file():
                parser.error(f"input script does not exist: {input_script}")
            play_text = schedule_from_script(input_script, args.frames,
                                             args.checkpoint)
        else:
            play_text = schedule(args.frames, args.start_frame, args.tap_interval,
                                 args.tap_length, args.start_mask,
                                 args.confirm_mask, args.checkpoint,
                                 args.tap_until)
    except ValueError as exc:
        parser.error(str(exc))
    play.write_text(play_text, encoding="ascii")
    command = [sys.executable, str(CAPTURE), "--emulator", str(emulator),
               "--rom", str(rom), "--play", str(play), "--out", str(out),
               "--timeout", str(args.timeout)]
    print("front_to_fight_capture: " + " ".join(command), flush=True)
    result = subprocess.run(command, cwd=ROOT, check=False)
    if out.is_dir():
        schedule_copy = out / "front_to_fight.play.txt"
        if not schedule_copy.exists():
            shutil.move(str(play), str(schedule_copy))
            play = schedule_copy
    print(f"play schedule: {play}")
    print(f"emulator log: {out / 'run.log'}")
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
