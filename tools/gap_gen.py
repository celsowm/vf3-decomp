#!/usr/bin/env python3
"""gap_gen.py - generate the translation modules for the still-unported
baseline entries with the repo's own translator (tools/oracle/translate_adapters.py).

The walk is static: it starts at every root and follows the branches in the
identity image, so no capture map is needed.  Each batch is a module of its
own; the modules are placed last in the router chain, so the older modules
keep the PCs they already own.

  python tools/gap_gen.py --batch 40 --size 40
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
AN = REPO / "extract" / "analysis"
WATCH = REPO / "tools" / "watch"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=40)
    ap.add_argument("--size", type=int, default=40)
    ap.add_argument("--start", type=int, default=0)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gap = json.load(open(AN / "gap_rank.json", encoding="utf-8"))
    total = len(gap)
    nbatches = (total + args.size - 1) // args.size
    b = 0
    off = args.start
    while off < total:
        b += 1
        sel = gap[off:off + args.size]
        name = f"vf3_gap_b{b:02d}_adapter"
        watch = WATCH / f"vf3_gap_b{b:02d}.txt"
        out = REPO / "src" / "fight" / f"{name}.c"
        lines = ["# The still-unported baseline entries (body-range union gap).",
                 "# Generated by tools/gap_watch.py; one root per entry."]
        for g in sel:
            lines.append(f"pc 0x{g['entry']:08x}")
        watch.write_text("\n".join(lines) + "\n", encoding="utf-8")
        cmd = [sys.executable, str(REPO / "tools" / "oracle" / "translate_adapters.py"),
               str(AN / "_empty_caps"),
               "--watch", str(watch),
               "--out", str(out),
               "--function", name,
               "--reuse-adapter", "src/fight/*.c"]
        # The batches are generated in order and each one reuses the claims of
        # the batches before it (a PC the earlier batch owns is the earlier
        # batch's).  The batches *after* this one are left out: their stale
        # claim sets would hide the callees this batch has to translate.
        for later in range(b + 1, nbatches + 1):
            cmd += ["--reuse-exclude", f"src/fight/vf3_gap_b{later:02d}_adapter.c"]
        if args.dry_run:
            print(" ".join(cmd))
            print(f"  {len(sel)} roots, {sum(g['new'] for g in sel)} B")
            off += args.size
            continue
        p = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
        tail = (p.stdout or "").strip().splitlines()[-1:] or [""]
        if p.returncode != 0:
            print(f"batch {b} FAILED: {p.stderr[-800:]}")
            return 1
        print(f"batch {b:02d}: {len(sel):3d} roots  {sum(g['new'] for g in sel):6d} B  "
              f"{out.name}  {tail[0]}")
        off += args.size
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
