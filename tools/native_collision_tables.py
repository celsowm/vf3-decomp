#!/usr/bin/env python3
"""Extract the retail fighter capsule masks and per-kind radius profiles.

The output is a C include used by ``src/native/collision.c``. The tool only
reads the binary image; it does not modify the input file.

Example:
  python tools/native_collision_tables.py extract/gamedata/1ST_READ.BIN \
      --output src/native/collision_tables.inc
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import struct
import sys

ADDRESS_MASK = 0x1FFFFFFF
MASK_TABLE = 0x0C110994
RADIUS_POINTERS = 0x0C10D390
KIND_COUNT = 13
CAPSULE_COUNT = 28


def read_bytes(data: bytes, base: int, address: int, size: int) -> bytes:
    offset = (address & ADDRESS_MASK) - (base & ADDRESS_MASK)
    if offset < 0 or size < 0 or offset + size > len(data):
        raise ValueError(
            f"{address:#010x} maps to file offset {offset:#x}, outside "
            f"the {len(data):#x}-byte image based at {base:#010x}"
        )
    return data[offset:offset + size]


def c_float(value: float) -> str:
    text = format(value, ".9g")
    if "." not in text and "e" not in text.lower():
        text += ".0"
    return text + "f"


def extract(data: bytes, base: int) -> tuple[list[int], list[list[float]], list[int]]:
    masks_raw = read_bytes(data, base, MASK_TABLE, KIND_COUNT * 4)
    masks = list(struct.unpack("<13I", masks_raw))
    pointers_raw = read_bytes(data, base, RADIUS_POINTERS, KIND_COUNT * 4)
    pointers = list(struct.unpack("<13I", pointers_raw))

    profiles: list[list[float]] = []
    for kind, pointer in enumerate(pointers):
        raw = read_bytes(data, base, pointer, CAPSULE_COUNT * 4)
        values = list(struct.unpack("<28f", raw))
        if any(not math.isfinite(value) or value < 0.0 for value in values):
            raise ValueError(f"kind {kind} at {pointer:#010x} has an invalid radius")
        profiles.append(values)
    return masks, profiles, pointers


def render(masks: list[int], profiles: list[list[float]], pointers: list[int]) -> str:
    rows = [
        "/* Generated by tools/native_collision_tables.py; do not edit by hand. */",
        "static const uint32_t vf3_native_collision_masks[VF3_NATIVE_CAPSULE_KIND_COUNT] = {",
    ]
    for start in range(0, len(masks), 4):
        chunk = ", ".join(f"UINT32_C(0x{value:08x})" for value in masks[start:start + 4])
        rows.append(f"    {chunk},")
    rows.extend([
        "};",
        "",
        "static const float vf3_native_collision_radii[VF3_NATIVE_CAPSULE_KIND_COUNT]",
        "    [VF3_NATIVE_CAPSULE_LIMIT] = {",
    ])
    for kind, (pointer, profile) in enumerate(zip(pointers, profiles)):
        rows.append(f"    /* actor kind {kind}, retail address 0x{pointer:08x} */ {{")
        for start in range(0, len(profile), 4):
            chunk = ", ".join(c_float(value) for value in profile[start:start + 4])
            rows.append(f"        {chunk},")
        rows.append("    },")
    rows.extend(["};", ""])
    return "\n".join(rows)


def number(text: str) -> int:
    try:
        value = int(text, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"invalid integer: {text}") from exc
    if not 0 <= value <= 0xFFFFFFFF:
        raise argparse.ArgumentTypeError("base address must fit in 32 bits")
    return value


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="raw executable image")
    parser.add_argument("--base", type=number, default=0x8C010000,
                        help="guest address corresponding to file offset zero")
    parser.add_argument("--output", type=Path, default=Path("-"),
                        help="C include output path, or - for stdout")
    args = parser.parse_args(argv)
    try:
        data = args.image.read_bytes()
        masks, profiles, pointers = extract(data, args.base)
        output = render(masks, profiles, pointers)
        if str(args.output) == "-":
            sys.stdout.write(output)
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(output, encoding="ascii", newline="\n")
    except (OSError, ValueError) as exc:
        print(f"native_collision_tables: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
