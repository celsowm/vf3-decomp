#!/usr/bin/env python3
"""Capture fighter motion fields while replaying timed input pulses.

The tool writes a frame-clock ``VF3_PLAY`` schedule and delegates the RAM
watch to ``mem_watch.py``. It is meant for offline reverse engineering; the
result is evidence about a particular savestate and input schedule, not an
action-to-motion mapping.

Example:
  python tools/native_motion_input_probe.py \
      --state extract/analysis/flycast_pose_capture_s26_v1/data/vf3_47.state \
      --emulator tools/emu/flycast-build/flycast_v3.exe \
      --out extract/analysis/motion_probe_s47_v1 --frames 180 \
      --actor 0x0c1fefe4 --actor 0x0c20138c \
      --pulse 15:30:0x4 --pulse 45:60:0x2 --pulse 75:90:0x1 \
      --pulse 105:120:0x8

Each pulse is START:END:MASK, with END exclusive. KEYF masks use the
vf3script input convention; frame zero and every pulse boundary are neutral.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
ANALYSIS = ROOT / "extract" / "analysis"
MEM_WATCH = ROOT / "tools" / "mem_watch.py"
DEFAULT_EMULATOR = ROOT / "tools" / "emu" / "flycast-build" / "flycast_v3.exe"


def integer(text: str) -> int:
    try:
        value = int(text, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"invalid integer: {text}") from exc
    if value < 0:
        raise argparse.ArgumentTypeError("value must be nonnegative")
    return value


def pulse(text: str) -> tuple[int, int, int]:
    try:
        start_text, end_text, mask_text = text.split(":", 2)
        start, end, mask = int(start_text, 0), int(end_text, 0), int(mask_text, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            "expected START:END:MASK, e.g. 15:30:0x4") from exc
    if start < 1 or end <= start or not 0 <= mask <= 0xFFFF:
        raise argparse.ArgumentTypeError("pulse range or 16-bit mask is invalid")
    return start, end, mask


def repo_path(path: Path) -> Path:
    return path.resolve() if path.is_absolute() else (ROOT / path).resolve()


def play_text(frames: int, pulses: list[tuple[int, int, int]]) -> str:
    events: dict[int, int] = {0: 0}
    previous_end = -1
    for start, end, mask in sorted(pulses):
        if start <= previous_end:
            raise ValueError("input pulses must not overlap")
        if end >= frames - 1:
            raise ValueError("every pulse must end before the EXITF frame")
        events[start] = mask
        events[end] = 0
        previous_end = end
    rows = [f"{frame} KEYF 0x{mask:x}" for frame, mask in sorted(events.items())]
    rows.append(f"{frames - 1} EXITF")
    return "# Generated by tools/native_motion_input_probe.py\n" + "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--state", required=True, type=Path,
                        help="retained Flycast savestate")
    parser.add_argument("--emulator", type=Path, default=DEFAULT_EMULATOR,
                        help=f"instrumented Flycast executable (default: {DEFAULT_EMULATOR})")
    parser.add_argument("--out", required=True, type=Path,
                        help="new output directory under extract/analysis")
    parser.add_argument("--frames", type=int, default=180,
                        help="frame-clock replay length (default: 180)")
    parser.add_argument("--actor", type=integer, action="append", required=True,
                        help="fighter actor record address; repeat for each fighter")
    parser.add_argument("--pulse", type=pulse, action="append", default=[],
                        help="timed START:END:MASK input pulse; repeatable")
    parser.add_argument("--timeout", type=int, default=900,
                        help="maximum emulator runtime in seconds (default: 900)")
    parser.add_argument("--limit", type=int, default=0,
                        help="maximum decoded hits to print (0 prints all)")
    args = parser.parse_args(argv)

    state = repo_path(args.state)
    emulator = repo_path(args.emulator)
    out = repo_path(args.out)
    try:
        out.relative_to(ANALYSIS.resolve())
    except ValueError:
        parser.error("--out must be inside extract/analysis")
    if args.frames < 2 or args.timeout < 0 or args.limit < 0:
        parser.error("--frames must be at least 2; --timeout and --limit cannot be negative")
    if len(set(args.actor)) != len(args.actor):
        parser.error("--actor addresses must be unique")
    for start, end, _mask in args.pulse:
        if end >= args.frames - 1:
            parser.error("every pulse must end before the EXITF frame")
    if not state.is_file():
        parser.error(f"savestate does not exist: {state}")
    if not emulator.is_file():
        parser.error(f"emulator does not exist: {emulator}")
    if not MEM_WATCH.is_file():
        parser.error(f"memory watcher is missing: {MEM_WATCH}")
    if out.exists():
        parser.error(f"refusing to replace existing output directory: {out}")
    try:
        schedule = play_text(args.frames, args.pulse)
    except ValueError as exc:
        parser.error(str(exc))

    out.mkdir(parents=True)
    play = out / "input_schedule.txt"
    play.write_text(schedule, encoding="ascii")
    ranges = []
    for actor in args.actor:
        # The actor's selected motion, current phase, and loop length.
        ranges.extend((f"0x{actor + 0x3C:08x}:2",
                       f"0x{actor + 0x3E:08x}:4",
                       f"0x{actor + 0x1A00:08x}:2"))
    metadata = {
        "diagnostic_only": True,
        "state": str(state),
        "emulator": str(emulator),
        "frames": args.frames,
        "actors": [f"0x{actor:08x}" for actor in args.actor],
        "pulses": [
            {"start": start, "end_exclusive": end, "mask": f"0x{mask:04x}"}
            for start, end, mask in sorted(args.pulse)
        ],
        "watch_ranges": ranges,
        "limitations": [
            "Motion IDs are reported without assigning action names.",
            "A changed motion ID alone does not identify the input's game meaning.",
        ],
    }
    (out / "capture.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    command = [sys.executable, str(MEM_WATCH), str(state)]
    for watch_range in ranges:
        command.extend(("--watch-range", watch_range))
    command.extend(("--play", str(play), "--emulator", str(emulator),
                    "--out-dir", str(out), "--name", "motion_fields",
                    "--frames", str(args.frames), "--changes-only",
                    "--limit", str(args.limit), "--timeout", str(args.timeout)))
    print(f"native_motion_input_probe: {state.name}, {args.frames} frames, "
          f"{len(args.actor)} actor(s), {len(args.pulse)} pulse(s)", flush=True)
    result = subprocess.run(command, cwd=ROOT, check=False)
    print(f"schedule: {play}")
    print(f"capture metadata: {out / 'capture.json'}")
    print(f"memory trace: {out / 'motion_fields.bin'}")
    print(f"emulator log: {out / 'motion_fields.log'}")
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
