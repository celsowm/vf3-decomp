#!/usr/bin/env python3
"""aica_arm_mix.py - what the ARM7's firmware actually executes.

The reference's ARM observer recorded every memory access the ARM7 made
(`vf3_28_traced.arm`, regenerated by tools/oracle/arm_observer.py).  Each
record carries the ARM7's program counter, so the instruction at that counter
is the one that made the access.  The firmware itself is the game's own
`SNDDRV.BIN` (the guest uploads it into the sound RAM), and the ARM7 fetches
from `aica_ram[pc & 0x1FFFFF]`, so the opcode is at the same offset in the
file.

This tool decodes those opcodes and reports the instruction mix, which is
the scope an ARM7 interpreter has to cover.

    python tools/aica_arm_mix.py
    python tools/aica_arm_mix.py --trace extract/analysis/audio_arm_observer_v3/vf3_28_traced.arm
"""
from __future__ import annotations

import argparse
import collections
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools" / "oracle"))

FIRMWARE = REPO / "extract" / "gamedata" / "SNDDRV.BIN"
DEFAULT_TRACE = REPO / "extract" / "analysis" / "audio_arm_observer_v3" / "vf3_28_traced.arm"


def trace_records(path: Path):
    """The observer's records (the same reader the oracle's own tool uses)."""
    with path.open("rb") as f:
        if f.read(8) != b"VF3ARM1\0":
            raise ValueError("unsupported ARM trace")
        previous = 0
        while data := f.read(40):
            if len(data) != 40:
                raise ValueError("truncated ARM record")
            seq, cycle, pc, op, addr, value, size, store = struct.unpack("<QQ6I", data)
            if seq != previous + 1 or size not in (1, 2, 4) or store not in (0, 1):
                raise ValueError("invalid ARM record")
            previous = seq
            yield dict(seq=seq, cycle=cycle, pc=pc, opcode=op, address=addr,
                       value=value, size=size, store=bool(store))


def classify(op: int) -> str:
    """The ARM instruction class of an opcode."""
    cond = op >> 28
    if cond == 0xF:
        return "undefined/extension"
    group = (op >> 25) & 7
    if group == 0:
        if (op >> 4) & 1:
            return "multiply/multiply-long"
        return "data-processing"
    if group == 1:
        return "data-processing (immediate)"
    if group == 2:
        return "load/store (immediate)"
    if group == 3:
        return "load/store (register offset)"
    if group == 4:
        return "load/store multiple"
    if group == 5:
        return "branch"
    if group == 6:
        return "coprocessor"
    return "SWI / branch-exchange"


def data_processing(op: int) -> str:
    """The data-processing operation's name."""
    names = ["AND", "EOR", "SUB", "RSB", "ADD", "ADC", "SBC", "RSC",
             "TST", "TEQ", "CMP", "CMN", "ORR", "MOV", "BIC", "MVN"]
    return names[(op >> 21) & 0xF]


def load_store(op: int) -> str:
    """The load/store operation's name and its addressing mode."""
    opc = (op >> 20) & 3
    names = {0: "STR", 1: "LDR", 2: "LDRB", 3: "STRB"}
    base = names[opc]
    if opc == 1 and (op & 0x10):
        base = "LDRH" if not (op & 0x20) else "LDRSB"
    bits = (op >> 22) & 3
    mode = {0: "immediate", 1: "register", 2: "register+offset", 3: "immediate+offset"}[bits]
    return f"{base} ({mode})"


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--trace", type=Path, default=DEFAULT_TRACE)
    ap.add_argument("--firmware", type=Path, default=FIRMWARE)
    args = ap.parse_args()
    if not args.trace.is_file():
        print(f"aica_arm_mix: {args.trace} missing")
        return 2
    fw = args.firmware.read_bytes()

    classes = collections.Counter()
    ops = collections.Counter()
    pcs = collections.Counter()
    total = 0
    for r in trace_records(args.trace):
        total += 1
        pc = r["pc"]
        if pc + 4 <= len(fw):
            op = struct.unpack_from("<I", fw, pc)[0]
        else:
            op = r["opcode"]
        kind = classify(op)
        if kind == "data-processing" or kind == "data-processing (immediate)":
            kind += f": {data_processing(op)}"
        elif kind.startswith("load/store ("):
            kind = load_store(op)
        classes[kind] += 1
        ops[op] += 1
        pcs[pc] += 1

    print(f"{total} records, {len(pcs)} distinct PCs, {len(ops)} distinct opcodes\n")
    print("the instruction mix (by the accesses each instruction made):")
    for kind, n in classes.most_common():
        print(f"  {n:7d}  {kind}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
