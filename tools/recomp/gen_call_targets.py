#!/usr/bin/env python3
"""gen_call_targets.py - static call-target table for the standalone native tick.

  python tools/recomp/gen_call_targets.py [fxr_tick_s*.bin ...] [--out src/fight/call_targets.c]

vf3_matrix_family() must tell a real call target (jsr/bsr/jmp-tail destination: it owns
its pr and runs until it returns) from a fragment seed inside a function (it must hand its
continuation back to the adapter that forwarded it). The whole-tick verification harness
answers that from the oracle's records of the one tick it replays; a standalone run has no
oracle, so the answer is baked in: the union of every entry the oracle saw called in any
captured fight tick (extract/analysis/fxr_tick_s*.bin; see docs/re/oracle_recomp.md).
Entries are physical (& 0x1FFFFFFF), sorted, looked up by bisection.
"""
import argparse
import glob
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
A = REPO / 'extract' / 'analysis'
NREG = 54
MAGIC = 0x31584656


def entries(path):
    data = path.read_bytes()
    words = struct.unpack(f'<{len(data) // 4}I', data)
    if not words or words[0] != MAGIC:
        raise SystemExit(f'{path}: not an fxr record file')
    i = 1
    found = set()
    while i + 4 + 2 * NREG + 1 <= len(words):
        found.add(words[i] & 0x1FFFFFFF)
        nw = words[i + 4 + 2 * NREG]
        i += 5 + 2 * NREG + 3 * nw
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('files', nargs='*')
    ap.add_argument('--out', default=str(REPO / 'src' / 'fight' / 'call_targets.c'))
    a = ap.parse_args()
    files = [Path(f) for f in a.files] or [Path(f) for f in sorted(glob.glob(str(A / 'fxr_tick_s*.bin')))
                                           if not f.endswith('_stats.csv')]
    allentries = set()
    for f in files:
        got = entries(f)
        print(f'{f.name}: {len(got)} entries', file=sys.stderr)
        allentries |= got
    lines = [
        '/* call_targets.c - GENERATED by tools/recomp/gen_call_targets.py; do not edit.',
        ' *',
        f' * Entries the oracle saw called in {len(files)} captured fight ticks ({len(allentries)} in all).',
        ' * See the generator for why the standalone tick needs the list. */',
        '#include "fight/native_tick.h"',
        '',
        'static const uint32_t call_targets[] = {',
    ]
    ordered = sorted(allentries)
    for k in range(0, len(ordered), 6):
        lines.append('    ' + ' '.join(f'0x{e:08x}u,' for e in ordered[k:k + 6]))
    lines += [
        '};',
        '',
        'int vf3_native_call_target(uint32_t entry)',
        '{',
        '    unsigned lo = 0, hi = sizeof call_targets / sizeof call_targets[0];',
        '    while (lo < hi) {',
        '        unsigned mid = (lo + hi) / 2;',
        '        if (call_targets[mid] < entry) lo = mid + 1;',
        '        else hi = mid;',
        '    }',
        '    return lo < sizeof call_targets / sizeof call_targets[0] && call_targets[lo] == entry;',
        '}',
        '',
    ]
    Path(a.out).write_text('\n'.join(lines), newline='\n')
    print(f'wrote {a.out} ({len(allentries)} entries)', file=sys.stderr)


if __name__ == '__main__':
    main()
